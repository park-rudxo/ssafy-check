// 이 확장은 두 가지 방식으로 배포된다.
//
//  unpacked - Release zip 을 받아 "압축 해제 → 폴더 선택"으로 설치한 경우.
//             갱신을 업데이트.bat 이 담당하므로, 팝업에 업데이트 확인 버튼과
//             "받아둔 파일 적용하기" 안내가 있어야 한다.
//
//  webstore - 크롬 웹스토어에서 설치한 경우. 갱신은 크롬이 알아서 하므로
//             업데이트 UI 도, GitHub 릴리스를 확인하는 동작도 필요 없다.
//             업데이트.bat 이 아예 들어 있지 않아서, 그걸 실행하라는 안내가
//             남아 있으면 사용자에게 없는 파일을 가리키게 된다.
//
// 저장소에는 항상 unpacked 로 둔다. 웹스토어 제출용 zip 을 만들 때만
// .github/workflows/release-zip.yml 이 이 파일을 webstore 로 바꿔 넣는다.
// 두 빌드의 차이가 이 한 줄뿐이라, 무엇이 다른지 확인하기 쉽다.
//
// self 에 붙이는 이유: 팝업(window)과 백그라운드 서비스 워커(importScripts)
// 양쪽에서 같은 코드로 읽어야 하기 때문이다.
self.BUILD_TARGET = "unpacked";
